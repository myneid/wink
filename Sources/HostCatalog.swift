import Foundation

// Every host Wink knows, in one place: Blink's hosts, the hosts you add or
// edit in Wink, and the hosts in your ~/.ssh/config.
//
// Blink's host database is an archive Blink syncs through iCloud, so Wink
// never writes to it. Your edits live in ~/.config/wink/hosts.json instead: an
// entry there replaces the Blink host with the same name, and `hidden` lists
// Blink hosts to leave out. From both, Wink writes blink_hosts.conf, the file
// its connections (and other terminals, if you turn that on) include.
//
// The app copies Blink's hosts to blink_hosts.json whenever it reads them, so
// the host picker never needs access to Blink's container.

struct HostEdits: Codable {
  var hosts: [BlinkHost] = []
  var hidden: [String] = []
}

struct CatalogHost {
  enum Source { case blink, edited, wink, sshConfig }
  var host: BlinkHost
  var source: Source
  var hidden = false

  var isEditable: Bool { source != .sshConfig }
}

enum HostCatalog {
  static let blinkCacheURL = BlinkConfig.winkDir.appendingPathComponent("blink_hosts.json")
  static let editsURL = BlinkConfig.winkDir.appendingPathComponent("hosts.json")

  struct BlinkCache: Codable {
    var hosts: [BlinkHost] = []
    /// Blink key name -> OpenSSH public key.
    var keys: [String: String] = [:]
  }

  struct Snapshot {
    var hosts: [CatalogHost]
    /// Key names a host can use: Blink's keys and your local private keys.
    var keyNames: [String]
    var blinkLoaded: Bool
  }

  // MARK: - Storage

  static func writeBlinkCache(hosts: [BlinkHost], keys: [String: String]) throws {
    try writePrivate(JSONEncoder().encode(BlinkCache(hosts: hosts, keys: keys)), to: blinkCacheURL)
  }

  static func blinkCache() -> BlinkCache? {
    (try? Data(contentsOf: blinkCacheURL)).flatMap { try? JSONDecoder().decode(BlinkCache.self, from: $0) }
  }

  static func edits() -> HostEdits {
    (try? Data(contentsOf: editsURL)).flatMap { try? JSONDecoder().decode(HostEdits.self, from: $0) } ?? HostEdits()
  }

  static func save(_ edits: HostEdits) throws {
    let encoder = JSONEncoder()
    encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
    try writePrivate(encoder.encode(edits), to: editsURL)
    try writeConfig()
  }

  private static func writePrivate(_ data: Data, to url: URL) throws {
    try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true,
                                            attributes: [.posixPermissions: 0o700])
    try data.write(to: url, options: .atomic)
    try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
  }

  // MARK: - The merged list

  static func load(includeSSHConfig: Bool = true) -> Snapshot {
    let cache = blinkCache()
    let edits = edits()
    let edited = Dictionary(edits.hosts.map { ($0.sshAlias, $0) }, uniquingKeysWith: { a, _ in a })
    let hidden = Set(edits.hidden)
    var out: [CatalogHost] = []
    var seen = Set<String>()
    for h in cache?.hosts ?? [] where !seen.contains(h.sshAlias) {
      seen.insert(h.sshAlias)
      if let e = edited[h.sshAlias] {
        out.append(CatalogHost(host: e, source: .edited))
      } else {
        out.append(CatalogHost(host: h, source: .blink, hidden: hidden.contains(h.sshAlias)))
      }
    }
    for h in edits.hosts where !seen.contains(h.sshAlias) {
      seen.insert(h.sshAlias)
      out.append(CatalogHost(host: h, source: .wink))
    }
    if includeSSHConfig {
      for alias in LocalSSHConfig.hostAliases() where !seen.contains(alias) {
        seen.insert(alias)
        out.append(CatalogHost(host: BlinkHost(alias: alias), source: .sshConfig))
      }
    }
    out.sort { $0.host.alias.localizedCaseInsensitiveCompare($1.host.alias) == .orderedAscending }
    let keyNames = Set((cache?.keys.keys).map(Array.init) ?? []).union(LocalSSHConfig.localPrivateKeys().keys)
    return Snapshot(hosts: out, keyNames: keyNames.sorted(), blinkLoaded: cache != nil)
  }

  // MARK: - ssh config

  /// Writes blink_hosts.conf: your Wink hosts, then the Blink hosts you
  /// haven't edited or hidden.
  static func writeConfig() throws {
    let cache = blinkCache() ?? BlinkCache()
    let edits = edits()
    let replaced = Set(edits.hosts.map(\.sshAlias)).union(edits.hidden)
    var out = """
      # Generated by Wink: hosts you added or edited in Wink, then Blink Shell's
      # hosts. Rewritten whenever they change; edit hosts in Wink's host picker
      # (Hosts ▸ Connect to Host…), in Blink, or override them in ~/.ssh/config.


      """
    if !edits.hosts.isEmpty { out += "# Wink\n\n" }
    for h in edits.hosts { out += block(h, keys: cache.keys) }
    out += "# Blink\n\n"
    for h in cache.hosts where !replaced.contains(h.sshAlias) { out += block(h, keys: cache.keys) }
    try FileManager.default.createDirectory(at: BlinkConfig.winkDir, withIntermediateDirectories: true)
    try out.write(to: BlinkConfig.hostsConfURL, atomically: true, encoding: .utf8)
    try BlinkConfig.writeLaunchConfig()
  }

  /// The Wink hosts alone, for the copy of your config that goes to Blink.
  static func winkHostsConfig() -> String {
    let keys = blinkCache()?.keys ?? [:]
    return edits().hosts.map { block($0, keys: keys) }.joined()
  }

  static func block(_ h: BlinkHost, keys: [String: String]) -> String {
    var out = "Host \(h.sshAlias)\n"
    if let v = h.hostName { out += "  HostName \(v)\n" }
    if let v = h.user { out += "  User \(quote(v))\n" }
    if let v = h.port { out += "  Port \(v)\n" }
    if let key = h.key, key != "None", let path = identityPath(for: key, blinkPub: keys[key]) {
      out += "  IdentityFile \(quote(path))\n"
    }
    if let v = h.proxyCommand { out += "  ProxyCommand \(v)\n" }
    if let v = h.proxyJump { out += "  ProxyJump \(v)\n" }
    if h.forwardAgent { out += "  ForwardAgent yes\n" }
    for line in h.configLines { out += "  \(line)\n" }
    return out + "\n"
  }

  static func identityPath(for keyName: String, blinkPub: String?) -> String? {
    let fm = FileManager.default
    if keyName.hasPrefix("/") || keyName.hasPrefix("~") {
      return (keyName as NSString).expandingTildeInPath
    }
    let sshKey = fm.homeDirectoryForCurrentUser.appendingPathComponent(".ssh").appendingPathComponent(keyName)
    // ~/.ssh/<name> only counts if it's the same key Blink has under that name.
    let sshKeyMatches: Bool = {
      guard fm.fileExists(atPath: sshKey.path) else { return false }
      guard let blinkPub else { return true }
      let local = (try? String(contentsOf: sshKey.appendingPathExtension("pub"), encoding: .utf8)) ?? ""
      return keyBlob(local) != nil && keyBlob(local) == keyBlob(blinkPub)
    }()
    let candidates = [
      BlinkConfig.keysDir.appendingPathComponent(keyName),
      sshKeyMatches ? sshKey : nil,
      BlinkConfig.keysDir.appendingPathComponent(keyName + ".pub"), // resolved via ssh-agent
    ].compactMap { $0 }
    return candidates.first { fm.fileExists(atPath: $0.path) }?.path
  }

  private static func keyBlob(_ pub: String) -> Substring? {
    let parts = pub.split(separator: " ")
    return parts.count >= 2 ? parts[1] : nil
  }

  private static func quote(_ s: String) -> String {
    s.contains(where: { $0 == " " || $0 == "\t" }) ? "\"\(s)\"" : s
  }
}

// MARK: - Tunnels and extra lines

extension BlinkHost {
  /// Blink keeps tunnels as LocalForward/RemoteForward/DynamicForward lines in
  /// the host's "SSH Config" text, so Wink does the same.
  static let tunnelKeywords = ["localforward": "L", "remoteforward": "R", "dynamicforward": "D"]

  /// The host's raw ssh config lines, without blanks and comments.
  var configLines: [String] {
    (sshConfigAttachment ?? "").split(whereSeparator: \.isNewline)
      .map { $0.trimmingCharacters(in: .whitespaces) }
      .filter { !$0.isEmpty && !$0.hasPrefix("#") }
  }

  /// Tunnels as "L 8080 localhost:80", "R 9000 localhost:9000", "D 1080".
  var tunnels: [String] {
    configLines.compactMap { line in
      let (key, value) = LocalSSHConfig.split(line)
      return Self.tunnelKeywords[key].map { "\($0) \(value)" }
    }
  }

  /// Raw lines that aren't tunnels.
  var extraLines: [String] {
    configLines.filter { Self.tunnelKeywords[LocalSSHConfig.split($0).0] == nil }
  }

  mutating func setConfig(tunnels: [String], extra: [String]) {
    let names = ["L": "LocalForward", "R": "RemoteForward", "D": "DynamicForward"]
    let lines = tunnels.compactMap { t -> String? in
      let parts = t.split(separator: " ", maxSplits: 1).map(String.init)
      guard parts.count == 2, let name = names[parts[0].uppercased()] else { return nil }
      return "\(name) \(parts[1])"
    } + extra
    sshConfigAttachment = lines.isEmpty ? nil : lines.joined(separator: "\n")
  }
}
